export function formatSummaryForDisplay(summary: SummaryResult): string {
  let output = "";
  
  output += "◆ الهدف (Objectif):\n";
  summary.objectif.forEach((item, i) => {
    output += `  ${i + 1}. ${item}\n`;
  });
  
  output += "\n◆ الشروط (Conditions):\n";
  summary.conditions.forEach((item, i) => {
    output += `  ${i + 1}. ${item}\n`;
  });
  
  output += "\n◆ الإجراءات (Procedures):\n";
  summary.procedures.forEach((item, i) => {
    output += `  ${i + 1}. ${item}\n`;
  });
  
  return output;
}
